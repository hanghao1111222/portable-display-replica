function normalizeS10ProQuery(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function searchS10ProCompatibility(query: string, limit = 8) {
  const normalizedQuery = normalizeS10ProQuery(query);
  if (normalizedQuery.length < 2) return [];

  const terms = normalizedQuery.split(/\s+/).filter(Boolean);

  return s10ProCompatibilityRecords
    .map((record) => {
      const model = normalizeS10ProQuery(record.model);
      const brandAndModel = normalizeS10ProQuery(`${record.brand} ${record.model}`);
      const searchable = normalizeS10ProQuery(
        `${record.brand} ${record.model} ${record.generation} ${record.ports}`,
      );

      if (!terms.every((term) => searchable.includes(term))) {
        return { record, score: 0 };
      }

      let score = terms.reduce((total, term) => {
        if (model === term) return total + 24;
        if (model.includes(term)) return total + 12;
        if (brandAndModel.includes(term)) return total + 8;
        return total + 3;
      }, 0);

      if (model === normalizedQuery || brandAndModel === normalizedQuery) score += 100;
      else if (model.includes(normalizedQuery) || brandAndModel.includes(normalizedQuery))
        score += 40;

      return { record, score };
    })
    .filter((result) => result.score > 0)
    .sort((a, b) => b.score - a.score || a.record.id - b.record.id)
    .slice(0, limit)
    .map((result) => result.record);
}
